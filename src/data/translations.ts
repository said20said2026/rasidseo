/**
 * Universal fallback translation dictionary for any of the other 30+ languages
 * Ensures complete responsiveness across all 40 languages even if a rare language is chosen!
 */
export function getLocalizedText(langCode: string, key: TranslationKey, fallback: string): string {
  // Check exact language match
  const dict = TRANSLATIONS[langCode];
  if (dict && dict[key]) {
    return dict[key]!;
  }

  // Handle region-variants like 'pt-BR' falling back to 'pt'
  if (langCode.includes('-')) {
    const baseCode = langCode.split('-')[0];
    const baseDict = TRANSLATIONS[baseCode];
    if (baseDict && baseDict[key]) {
      return baseDict[key]!;
    }
  }

  // If language is English or any non-Arabic language without a full dictionary,
  // return English translation as the high-quality international default
  if (langCode !== 'ar') {
    const enDict = TRANSLATIONS['en'];
    if (enDict && enDict[key]) {
      return enDict[key]!;
    }
  }

  // Default to Arabic or provided fallback
  const arDict = TRANSLATIONS['ar'];
  if (arDict && arDict[key]) {
    return arDict[key]!;
  }

  return fallback;
}
